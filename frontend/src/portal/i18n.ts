export type TKey = keyof typeof DICT

interface LangState {
  lang: Lang
  setLang: (l: Lang) => void
}

export const usePortalLang = create<LangState>()(
  persist((set) => ({ lang: navigator.language?.toLowerCase().startsWith('zh') ? 'zh' : 'en', setLang: (lang) => set({ lang }) }), {
    name: 'cloudsail-portal-lang',
  }),
)

export function useT() {
  const lang = usePortalLang((s) => s.lang)
  return (key: TKey, vars?: Record<string, string | number>) => {
    let s: string = DICT[key]?.[lang === 'zh' ? 0 : 1] ?? key
    if (vars) Object.entries(vars).forEach(([k, v]) => (s = s.replace(`{${k}}`, String(v))))
    return s
  }
}

export type T = ReturnType<typeof useT>

/** 订单状态 / 资金类型等动态 key */
export function tStatus(t: T, prefix: 'status' | 'txn' | 'recharge', value?: string | null): string {
  if (!value) return '-'
  const key = `${prefix}_${value}` as TKey
  return key in DICT ? t(key) : value
}
